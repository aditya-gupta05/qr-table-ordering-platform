"""PDF cleaning measurement (Phase 4, WP2). Does cleaning the extracted PDF text change what the chunker produces?

Run: cd api && uv run python ../eval/retrieval/pdf_cleaning.py
Output: eval/results/phase4/pdf_cleaning.{json,md}

Measured, for the generated corpus/menu.pdf:
  * size: characters and bge tokens, raw vs cleaned (what boilerplate costs the embedder)
  * item completeness: a menu item is "complete in one chunk" when a single chunk holds its name, its price AND the
    first six words of its description. Dot leaders (". . . . ." x 28 per dish) push the description away from the
    name and price, so raw text splits dishes across chunks more often at small chunk sizes.
  * the price-deletion bug: the first cleaner dropped lines that repeat on >= 50% of pages after digits were
    normalised ("$11.50" -> "$#.#"), which is every price line. Re-created here as `naive_clean`.
"""

import json
import re
import sys
from collections import Counter
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(REPO / "api"))

from app.retrieval.chunking import ChunkSpec, TokenCounter, chunk_document  # noqa: E402
from app.retrieval.clean import _norm_key  # noqa: E402
from app.retrieval.embedder import load_chunk_tokenizer  # noqa: E402
from app.retrieval.parse import extract_pdf_pages, parse_pdf  # noqa: E402
from app.retrieval.settings import get_retrieval_settings  # noqa: E402

PRICE = re.compile(r"\$\d+\.\d\d")
OUT = REPO / "eval" / "results" / "phase4"
SPECS = {
    "fixed_128_o0": ChunkSpec("fixed_token", 128, 0),
    "fixed_128_o30": ChunkSpec("fixed_token", 128, 38),
    "recursive_128_o15": ChunkSpec("recursive_md", 128, 19),
    "fixed_256_o0": ChunkSpec("fixed_token", 256, 0),
}


def naive_clean(pages: list[str]) -> str:
    """The first attempt: any line (digits normalised) that occurs on >= half the pages is boilerplate."""
    per = [[ln.strip() for ln in p.splitlines()] for p in pages]
    seen = Counter()
    for lines in per:
        seen.update({_norm_key(ln) for ln in lines if ln})
    min_pages = max(2, int(len(pages) * 0.5 + 0.999))
    bad = {k for k, c in seen.items() if c >= min_pages}
    return "\n\n".join(
        "\n".join(ln for ln in lines if ln and _norm_key(ln) not in bad) for lines in per
    )


def norm(s: str) -> str:
    return " ".join(s.split())


def main() -> None:
    pdf = REPO / "api" / "corpus" / "menu.pdf"
    menu = json.loads((REPO / "api" / "seed" / "menu.json").read_text())
    items = [i for c in menu["categories"] for i in c["items"]]
    counter = TokenCounter(load_chunk_tokenizer())
    get_retrieval_settings()
    pages = extract_pdf_pages(pdf)
    raw = parse_pdf(pdf, "menu_pdf", clean=False).content
    clean = parse_pdf(pdf, "menu_pdf").content
    naive = naive_clean(pages)

    # PDF-listed items only: those whose name appears in the text
    listed = [i for i in items if i["name"] in clean]
    res: dict = {
        "pages": len(pages),
        "items_in_pdf": len(listed),
        "size": {
            name: {
                "chars": len(t),
                "tokens": counter.count(t),
                "prices_kept": len(PRICE.findall(t)),
            }
            for name, t in (("raw", raw), ("cleaned", clean), ("naive_cleaner_bug", naive))
        },
        "completeness": {},
    }
    for cname, spec in SPECS.items():
        res["completeness"][cname] = {}
        for name, text in (("raw", raw), ("cleaned", clean)):
            chunks = [norm(c.text) for c in chunk_document(text, spec, counter)]
            ok = 0
            for it in listed:
                desc6 = norm(" ".join(it["description"].split()[:6]))
                price = f"${it['price_cents'] / 100:.2f}"
                ok += any(it["name"] in c and price in c and desc6 in c for c in chunks)
            res["completeness"][cname][name] = {
                "chunks": len(chunks),
                "complete_items": ok,
                "rate": round(ok / len(listed), 3),
            }
    (OUT / "pdf_cleaning.json").write_text(json.dumps(res, indent=2))
    L = [
        "# Phase 4: PDF cleaning, raw vs cleaned",
        "",
        "Generated by `eval/retrieval/pdf_cleaning.py` on `api/corpus/menu.pdf` "
        f"({res['pages']} pages, {res['items_in_pdf']} dishes listed).",
        "",
        "| text | chars | bge tokens | price strings kept |",
        "|---|---|---|---|",
    ]
    for k, v in res["size"].items():
        L.append(f"| {k} | {v['chars']} | {v['tokens']} | {v['prices_kept']} |")
    L += [
        "",
        "Share of dishes whose name, price and first six description words sit in ONE chunk:",
        "",
        "| chunk config | raw chunks | raw complete | cleaned chunks | cleaned complete |",
        "|---|---|---|---|---|",
    ]
    for c, v in res["completeness"].items():
        L.append(
            f"| {c} | {v['raw']['chunks']} | {v['raw']['complete_items']}/{res['items_in_pdf']} ({v['raw']['rate']:.1%}) "
            f"| {v['cleaned']['chunks']} | {v['cleaned']['complete_items']}/{res['items_in_pdf']} ({v['cleaned']['rate']:.1%}) |"
        )
    (OUT / "pdf_cleaning.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
